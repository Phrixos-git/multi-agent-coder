func TestPiBackendCollectsWorktreePatchWithoutPromptFileContents(t *testing.T) {
	root := t.TempDir()
	runPiTestGit(t, root, "init", "-q")
	runPiTestGit(t, root, "config", "user.email", "test@example.invalid")
	runPiTestGit(t, root, "config", "user.name", "Test")
	if err := os.WriteFile(filepath.Join(root, "starting.go"), []byte("package sample\n// private source body\n"), 0600); err != nil {
		t.Fatal(err)
	}
	runPiTestGit(t, root, "add", ".")
	runPiTestGit(t, root, "commit", "-qm", "init")
	executable := filepath.Join(t.TempDir(), "fake-pi")
	script := `#!/bin/sh
IFS= read -r prompt
case "$prompt" in *"private source body"*) exit 8;; esac
printf 'package sample\n// generated by fake Pi\n' > generated.go
printf '%s\n' '{"id":"mac-prompt","type":"response","success":true,"command":"prompt"}' '{"type":"tool_execution_end","toolName":"bash","result":{"content":[{"type":"text","text":"go test ./... PASS"}]}}' '{"type":"agent_end","messages":[{"role":"assistant","content":[{"type":"text","text":"Implemented generated.go. Tests passed."}]}]}' '{"type":"agent_settled"}'
`
	if err := os.WriteFile(executable, []byte(script), 0700); err != nil {
		t.Fatal(err)
	}
	cfg := config.Config{RepositoryRoot: root, PiExecutable: executable, PiProvider: "local-qwen", PiModel: "qwen", CoderBackend: "pi"}
	backend := NewPiBackend(cfg)
	raw, err := backend.Run(context.Background(), PromptInput{Role: RoleCoder, Task: "add a generated file", Files: []File{{Path: "starting.go", Content: "must not be sent"}}})
	if err != nil {
		t.Fatal(err)
	}
	var got struct {
		Status           string   `json:"status"`
		Role             string   `json:"role"`
		Summary          string   `json:"summary"`
		Backend          string   `json:"backend"`
		Patch            string   `json:"patch"`
		ChangedFiles     []string `json:"changed_files"`
		ExecutionResults []string `json:"execution_results"`
		Warnings         []string `json:"warnings"`
		Artifacts        []any    `json:"artifacts"`
	}
	if err := json.Unmarshal([]byte(raw), &got); err != nil {
		t.Fatal(err)
	}
	if got.Status != "success" || got.Role != "coder" || got.Backend != "pi" || len(got.Artifacts) != 0 {
		t.Fatalf("Pi result = %+v", got)
	}
	if !strings.Contains(got.Patch, "generated by fake Pi") || len(got.ChangedFiles) != 1 || got.ChangedFiles[0] != "generated.go" {
		t.Fatalf("patch/files = %q %#v", got.Patch, got.ChangedFiles)
	}
	if len(got.ExecutionResults) != 1 || !strings.Contains(got.ExecutionResults[0], "PASS") {
		t.Fatalf("execution results = %#v", got.ExecutionResults)
	}
}

func TestPiPromptContainsPathAndSelfFixLimit(t *testing.T) {
	prompt := buildPiPrompt(PromptInput{Role: RoleCoder, Task: "implement", Files: []File{{Path: "internal/a.go", Content: "do not include"}}})
	if !strings.Contains(prompt, "internal/a.go") || strings.Contains(prompt, "do not include") || !strings.Contains(prompt, "at most 3 implementation/test repair cycles") || !strings.Contains(prompt, "Agent JSON artifact format") {
		t.Fatalf("unexpected prompt: %q", prompt)
	}
}

func TestPiFixerPromptDescribesRepairAndOmitsFileBodies(t *testing.T) {
	prompt := buildPiPrompt(PromptInput{Role: RoleFixer, Task: "repair defect", Requirements: []string{"smallest fix"}, Files: []File{{Path: "internal/foo.go", Content: "secret file body"}}, AdditionalContext: "review says nil panic"})
	for _, want := range []string{"software repair agent", "current implementation that needs repair", "review findings", "at most 3 repair/test cycles", "Targeted"} {
		if !strings.Contains(strings.ToLower(prompt), strings.ToLower(want)) {
			t.Errorf("fixer prompt missing %q: %s", want, prompt)
		}
	}
	if !strings.Contains(prompt, "internal/foo.go") || strings.Contains(prompt, "secret file body") {
		t.Fatalf("fixer prompt leaked file body: %q", prompt)
	}
}

func TestPiBackendRejectsMalformedRPCAndMissingSettled(t *testing.T) {
	for name, output := range map[string]string{"malformed": "printf 'not-json\\n'\n", "missing_settled": "printf '%s\\n' '{\"id\":\"mac-prompt\",\"type\":\"response\",\"success\":true}'\n"} {
		t.Run(name, func(t *testing.T) {
			backend := newFakePiBackend(t, "read -r prompt\n"+output)
			raw, err := backend.Run(context.Background(), PromptInput{Role: RoleCoder, Task: "test"})
			if err != nil {
				t.Fatal(err)
			}
			var got struct {
				Status string `json:"status"`
				Error  struct {
					Kind string `json:"kind"`
				} `json:"error"`
			}
			if err := json.Unmarshal([]byte(raw), &got); err != nil {
				t.Fatal(err)
			}
			if got.Status != "error" || got.Error.Kind != "PiRPCError" && got.Error.Kind != "PiProcessError" {
				t.Fatalf("result = %+v", got)
			}
		})
	}
}

func TestPiBackendCancellationTerminatesProcess(t *testing.T) {
	backend := newFakePiBackend(t, "read -r prompt\nexec sleep 20\n")
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan string, 1)
	go func() {
		raw, err := backend.Run(ctx, PromptInput{Role: RoleCoder, Task: "cancel test"})
		if err != nil {
			done <- err.Error()
			return
		}
		var response struct {
			Error struct {
				Kind string `json:"kind"`
			} `json:"error"`
		}
		_ = json.Unmarshal([]byte(raw), &response)
		done <- response.Error.Kind
	}()
	time.Sleep(100 * time.Millisecond)
	cancel()
	select {
	case err := <-done:
		if !strings.Contains(err, "PiCancelledError") {
			t.Fatalf("error = %q", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("Pi process did not stop after cancellation")
	}
}

func TestPiBackendStopsAfterThreeRepairCycles(t *testing.T) {
	body := "read -r prompt\nprintf '%s\\n' '{\"id\":\"mac-prompt\",\"type\":\"response\",\"success\":true}'\n"
	for i := 0; i < 4; i++ {
		body += "printf '%s\\n' '{\"type\":\"turn_start\"}' '{\"type\":\"tool_execution_start\",\"toolCallId\":\"t" + strconv.Itoa(i) + "\",\"toolName\":\"bash\",\"args\":{\"command\":\"go test ./...\"}}' '{\"type\":\"tool_execution_end\",\"toolCallId\":\"t" + strconv.Itoa(i) + "\",\"toolName\":\"bash\",\"isError\":true,\"result\":{\"content\":[{\"type\":\"text\",\"text\":\"FAIL\"}]}}' '{\"type\":\"turn_end\"}'\n"
	}
	body += "printf '%s\\n' '{\"type\":\"agent_settled\"}'\n"
	backend := newFakePiBackend(t, body)
	raw, err := backend.Run(context.Background(), PromptInput{Role: RoleCoder, Task: "test repair loop"})
	if err != nil {
		t.Fatal(err)
	}
	var got struct {
		Status string `json:"status"`
		Error  struct {
			Kind string `json:"kind"`
		} `json:"error"`
		RepairCycles int `json:"repair_cycle_count"`
	}
	if err := json.Unmarshal([]byte(raw), &got); err != nil {
		t.Fatal(err)
	}
	if got.Status != "error" || got.Error.Kind != "PiRepairLimitError" || got.RepairCycles != 3 {
		t.Fatalf("result = %+v", got)
	}
}

func newFakePiBackend(t *testing.T, body string) *PiBackend {
	t.Helper()
	root := t.TempDir()
	runPiTestGit(t, root, "init", "-q")
	runPiTestGit(t, root, "config", "user.email", "test@example.invalid")
	runPiTestGit(t, root, "config", "user.name", "Test")
	if err := os.WriteFile(filepath.Join(root, "file.txt"), []byte("base\n"), 0600); err != nil {
		t.Fatal(err)
	}
	runPiTestGit(t, root, "add", ".")
	runPiTestGit(t, root, "commit", "-qm", "init")
	executable := filepath.Join(t.TempDir(), "fake-pi")
	if err := os.WriteFile(executable, []byte("#!/bin/sh\n"+body), 0700); err != nil {
		t.Fatal(err)
	}
	return NewPiBackend(config.Config{RepositoryRoot: root, PiExecutable: executable, PiProvider: "local-qwen", PiModel: "qwen"})
}

func runPiTestGit(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v: %s", args, err, out)
	}
}
